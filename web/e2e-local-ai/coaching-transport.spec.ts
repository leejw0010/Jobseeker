import {expect,test} from '@playwright/test';
import {API} from '../e2e/env';
const FIXTURE='http://127.0.0.1:8012';

test('synthetic HTTP provider → grounded AI/evidence → followup → debrief → redrill without implicit model calls',async({page,request})=>{
 const before=await (await request.get(`${FIXTURE}/counts`)).json();
 const app=await (await request.post(`${API}/track/applications`,{data:{company:'합성 검증 회사',position:'합성 개발 직무'}})).json();
 const item=await (await request.post(`${API}/track/applications/${app.id}/essays`,{data:{question_text:'합성 프로젝트',content:'합성 예시에서 오류 로그를 분류하고 원인을 비교했습니다.'}})).json();
 expect((await request.post(`${API}/track/versions/${item.versions[0].id}/submit`)).status()).toBe(200);
 const q=await (await request.post(`${API}/practice/questions`,{data:{category:'직무',text:'합성 프로젝트에서 문제를 분석하고 선택한 방법은 무엇인가요?',question_type:'project_deep_dive',competency_keys:['problem_solving']}})).json();
 const s=await (await request.post(`${API}/practice/sessions`,{data:{mode:'free',question_ids:[q.id],application_id:app.id,followups_enabled:true}})).json();
 const a=s.answers[0];
 await request.patch(`${API}/practice/answers/${a.id}`,{data:{transcript:'합성 예시에서 오류 로그를 분류하고 원인을 비교했습니다.'}});
 await page.goto(`/practice/sessions/${s.id}`);
 await page.locator(`#answer-${a.id}`).getByRole('button',{name:'답변 점검',exact:true}).click();
 await expect(page.locator('.coaching-panel')).toContainText('AI 코칭');
 await expect(page.getByText('질문 1개 · 인용 근거 1개')).toBeVisible();
 const checked=await (await request.get(`${API}/practice/sessions/${s.id}`)).json();
 expect(checked.answers[0].coaching_report).toMatchObject({method:'ai',input_status:'current',competency_evidence:{status:'analyzed'}});
 const countAfterCoach=await (await request.get(`${FIXTURE}/counts`)).json();
 expect(countAfterCoach.coach-before.coach).toBe(1);
 await page.getByText('내 답변으로 개선 틀 만들기',{exact:true}).click();
 await page.getByText('근거로 보는 답변별 코멘트',{exact:true}).click();
 await page.reload();
 await expect(page.locator('.coaching-panel')).toBeVisible();
 expect(await (await request.get(`${FIXTURE}/counts`)).json()).toEqual(countAfterCoach);
 // Existing current report is reused for the followup: zero additional model calls.
 const follow=await request.post(`${API}/practice/answers/${a.id}/followup`);
 expect(follow.status()).toBe(201);
 const child=(await follow.json()).answers[1];
 expect(child.question.text).toContain('어떤 방법으로 확인');
 expect(await (await request.get(`${FIXTURE}/counts`)).json()).toEqual(countAfterCoach);
 await request.patch(`${API}/practice/answers/${child.id}`,{data:{transcript:'합성 예시의 같은 로그를 다시 비교하여 변경 여부를 확인했습니다.'}});
 await request.post(`${API}/practice/sessions/${s.id}/finish`);
 await expect.poll(async()=> (await (await request.get(`${API}/practice/sessions/${s.id}`)).json()).debrief_status).toBe('done');
 const end=await (await request.get(`${API}/practice/sessions/${s.id}`)).json();
 expect(end.answers.every((x:{coaching_report:{method:string}})=>x.coaching_report.method==='ai')).toBe(true);
 expect(end.debrief.moments[0].quote).toBe('합성 예시에서 오류 로그를 분류하고 원인을 비교했습니다.');
 await page.reload();
 await expect(page.getByRole('heading',{name:'통합 코칭'})).toBeVisible();
 await page.getByText('기존 AI 디브리프의 근거와 원문',{exact:true}).click();
 await expect(page.getByText('합성 디브리프: 선택과 결과 확인을 연결해 설명하기',{exact:true})).toBeVisible();
 const finalCounts=await (await request.get(`${FIXTURE}/counts`)).json();
 expect(finalCounts.coach-before.coach).toBe(2); expect(finalCounts.debrief-before.debrief).toBe(1); expect(finalCounts.generate-before.generate).toBe(0);
 await page.getByRole('button',{name:'보완 항목 2개 다시 연습',exact:true}).click();
 await expect(page.getByRole('heading',{name:/보완 연습/})).toBeVisible();
 expect(await (await request.get(`${FIXTURE}/counts`)).json()).toEqual(finalCounts);
 await test.info().attach('synthetic-provider-counts.json',{body:JSON.stringify({before,after:finalCounts,scope:'Local canned HTTP responses; model quality unmeasured.'},null,2),contentType:'application/json'});
});
